import fs from 'node:fs/promises';
import path from 'node:path';
import { abortError } from '../utils/time.js';
import { plural } from '../utils/format.js';
import { idSuffix, suffixOfMarkdownName } from './conversation-names.js';
import { removeStaleTempFiles, writeAtomic } from './storage-service.js';
import { renderHtml } from './digest-html.js';

/*
 * The digest: digest/INDEX.md (one line per chat), a page per month listing the messages typed in
 * each chat with line anchors into its Markdown, and a self-contained, searchable index.html. It is
 * built from markdown/ (the anchors are positions in those files) and is deterministic, so a backup
 * that brings in nothing new rewrites nothing.
 */

const HTML_TURN_LIMIT = 800; // characters of each message kept in index.html
const MONTH_TURN_LIMIT = 400; // ... on the monthly pages
const PREVIEW_LIMIT = 160; // first-message preview in INDEX.md and the index.html rows
const NO_QUESTIONS = '(no typed questions; assistant opened with)';
const GENERATED = 'Generated by chatgpt-exporter; do not edit.';

export interface Turn { n: number; line: number; text: string; truncated: boolean }
export interface Chat {
  id: string;
  suffix: string;
  title: string;
  url: string;
  /** YYYY-MM-DD from the file name (the user's time zone, like the file name itself). */
  date: string;
  /** ISO, from the front matter. */
  created: string;
  updated: string;
  /** Relative to the archive, e.g. "markdown/2026-10-15 Jetstar … (996b3a8cc27b).md". */
  file: string;
  /** Folder name under projects/. */
  project: string | null;
  archived: boolean;
  /** The user's messages, cleaned and cut to HTML_TURN_LIMIT. */
  turns: Turn[];
  assistantTurns: number;
  /** The first reply, only when the user typed nothing. */
  fallback?: Turn;
}
export interface Lookups { projectOf: Map<string, string>; archived: Set<string> }

type Role = 'User' | 'Assistant';
export interface Transcript {
  id: string;
  title: string;
  url?: string;
  created?: string;
  updated?: string;
  /** `line` is the 1-based line of the turn's **Role:** marker. */
  turns: { role: Role; line: number; text: string }[];
}

const MARKER = /^\*\*(User|Assistant):\*\*$/;

/** Splits one Markdown file written by markdown-service into its front matter and turns. */
export function parseTranscript(source: string): Transcript {
  const lines = source.split('\n');
  const end = lines[0] === '---' ? lines.indexOf('---', 1) : -1;
  if (end < 0) throw new Error('no frontmatter');
  const meta = new Map<string, string>();
  for (const line of lines.slice(1, end)) {
    const sep = line.indexOf(': ');
    if (sep > 0) meta.set(line.slice(0, sep), line.slice(sep + 2));
  }
  const id = meta.get('id');
  const title = meta.get('title');
  if (!id || title === undefined) throw new Error('frontmatter lacks id or title');

  // A marker is a whole line after a blank one. Every marker but the first also follows the "---"
  // separator, so lookalikes pasted into a message aren't taken for new turns.
  const markers: { role: Role; index: number }[] = [];
  for (let i = end + 1; i < lines.length; i++) {
    const match = MARKER.exec(lines[i]);
    if (!match || lines[i - 1] !== '') continue;
    if (markers.length > 0 && lines[i - 2] !== '---') continue;
    markers.push({ role: match[1] as Role, index: i });
  }
  const turns = markers.map(({ role, index }, k) => {
    const stop = k + 1 < markers.length ? markers[k + 1].index - 2 : lines.length; // the next "---"
    const text = lines.slice(index + 1, stop).join('\n').replace(/^\n+|\n+$/g, '');
    return { role, line: index + 1, text };
  });
  return {
    id, title: parseTitle(title), url: meta.get('url'), created: meta.get('created'), updated: meta.get('updated'), turns,
  };
}

/** The title is written as a JSON string (tolerate a bare one); some end in "\n". */
function parseTitle(value: string): string {
  let title = value;
  try {
    const parsed: unknown = JSON.parse(value);
    if (typeof parsed === 'string') title = parsed;
  } catch {
    // Not JSON: use it as it is.
  }
  return title.replace(/\s+/g, ' ').trim();
}

/**
 * One line of plain text: code blocks and images become placeholders, control characters go (pasted
 * binary would make grep treat a whole month page as binary), whitespace collapses.
 */
export function cleanText(text: string): string {
  return text
    .replace(/```[\s\S]*?```/g, ' [code] ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' [image] ')
    .replace(/[\u0000-\u0008\u000e-\u001f\u007f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Cuts at the last word boundary before `limit` (unless that loses too much) and adds "…". */
export function truncate(text: string, limit: number): { text: string; truncated: boolean } {
  if (text.length <= limit) return { text, truncated: false };
  let cut = text.slice(0, limit);
  const space = cut.lastIndexOf(' ');
  if (space >= limit * 0.6) cut = cut.slice(0, space);
  else if (/[\uD800-\uDBFF]$/.test(cut)) cut = cut.slice(0, -1); // don't split a surrogate pair
  return { text: cut.replace(/[\s,;:.]+$/, '') + '…', truncated: true };
}

export function buildChat(file: string, source: string, lookups: Lookups): Chat {
  const t = parseTranscript(source);
  const name = path.posix.basename(file);
  const date = /^\d{4}-\d{2}-\d{2}(?= )/.exec(name)?.[0] ?? t.created?.slice(0, 10) ?? '';
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error('no date in the file name or frontmatter');
  const userTurns = t.turns.filter((turn) => turn.role === 'User');
  const firstReply = t.turns.find((turn) => turn.role === 'Assistant');
  const chat: Chat = {
    id: t.id,
    suffix: suffixOfMarkdownName(name) ?? idSuffix(t.id),
    title: t.title,
    url: t.url ?? `https://chatgpt.com/c/${t.id}`,
    date,
    created: t.created ?? date,
    updated: t.updated ?? t.created ?? date,
    file,
    project: lookups.projectOf.get(t.id) ?? null,
    archived: lookups.archived.has(t.id),
    turns: userTurns.map((turn, i) => ({ n: i + 1, line: turn.line, ...truncate(cleanText(turn.text), HTML_TURN_LIMIT) })),
    assistantTurns: t.turns.length - userTurns.length,
  };
  if (chat.turns.length === 0 && firstReply) {
    chat.fallback = { n: 0, line: firstReply.line, ...truncate(cleanText(firstReply.text), PREVIEW_LIMIT) };
  }
  return chat;
}

async function readList(file: string): Promise<Array<{ id: string; is_archived?: boolean }>> {
  try {
    const parsed: unknown = JSON.parse(await fs.readFile(file, 'utf-8'));
    return Array.isArray(parsed) ? (parsed as Array<{ id: string; is_archived?: boolean }>) : [];
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
}

/** Archived flags from conversations/index.json; project folders from projects/<name>/conversations/index.json. */
async function loadLookups(outputDir: string): Promise<Lookups> {
  const archived = new Set<string>();
  for (const item of await readList(path.join(outputDir, 'conversations', 'index.json'))) if (item.is_archived) archived.add(item.id);
  const projectOf = new Map<string, string>();
  const projectsDir = path.join(outputDir, 'projects');
  const folders: string[] = [];
  for (const entry of await fs.readdir(projectsDir, { withFileTypes: true }).catch(() => [])) {
    if (entry.isDirectory()) folders.push(entry.name);
  }
  for (const folder of folders.sort()) {
    for (const item of await readList(path.join(projectsDir, folder, 'conversations', 'index.json'))) projectOf.set(item.id, folder);
  }
  return { projectOf, archived };
}

/** Newest first by creation time (the front matter carries the offset), then by file name. */
function sortNewestFirst(chats: Chat[]): Chat[] {
  const time = (c: Chat) => Date.parse(c.created) || Date.parse(c.date);
  return chats.sort((a, b) => time(b) - time(a) || (a.file < b.file ? 1 : a.file > b.file ? -1 : 0));
}

function groupByMonth(chats: Chat[]): Array<[string, Chat[]]> {
  const months = new Map<string, Chat[]>();
  for (const chat of chats) {
    const month = chat.date.slice(0, 7);
    if (!months.has(month)) months.set(month, []);
    months.get(month)!.push(chat);
  }
  return [...months].sort((a, b) => (a[0] < b[0] ? 1 : -1));
}

// ---- Markdown pages ----

const linkText = (text: string) => (text || 'Untitled').replace(/[\\[\]|]/g, '\\$&');
const transcriptLink = (chat: Chat) => `[${linkText(chat.title)}](<../${chat.file.replace(/[<>]/g, (c) => encodeURIComponent(c))}>)`;
const tags = (chat: Chat) => (chat.project ? ` · project: ${chat.project}` : '') + (chat.archived ? ' · archived' : '');

function firstMessage(chat: Chat, limit: number): string {
  if (chat.turns.length) return truncate(chat.turns[0].text, limit).text;
  if (chat.fallback) return `${NO_QUESTIONS} ${truncate(chat.fallback.text, limit).text}`;
  return '(empty conversation)';
}

export function renderIndex(months: Array<[string, Chat[]]>, total: number): string {
  const out = [
    '# Conversation index',
    '',
    `${plural(total, 'conversation')}, newest first, grouped by month. One line per chat: date · title (linked`,
    'to the transcript) · the first message you typed · how many messages you typed. Line anchors (`L<n>`)',
    `are on the monthly pages. ${GENERATED}`,
    '',
    `Months: ${months.map(([month, list]) => `[${month}](${month}.md) (${list.length})`).join(' · ')}`,
  ];
  for (const [month, list] of months) {
    out.push('', `## ${month} (${list.length})`, '');
    for (const chat of list) {
      out.push(`- ${chat.date} · ${transcriptLink(chat)} · ${firstMessage(chat, PREVIEW_LIMIT)} · ${plural(chat.turns.length, 'turn')}${tags(chat)}`);
    }
  }
  return out.join('\n') + '\n';
}

export function renderMonth(month: string, list: Chat[], older?: string, newer?: string): string {
  const nav = ['[INDEX](INDEX.md)', older && `older: [${older}](${older}.md)`, newer && `newer: [${newer}](${newer}.md)`];
  const out = [
    `# ${month} — ${plural(list.length, 'conversation')}`,
    '',
    nav.filter(Boolean).join(' · '),
    '',
    'Each entry: title (linked to the transcript), date, how many messages you typed, ChatGPT link; then each',
    'message you typed, prefixed with the transcript line of its `**User:**` marker (open with',
    `\`Read … offset <n>\` or \`sed -n '<n>,+40p'\`). ${GENERATED}`,
  ];
  for (const chat of list) {
    out.push('', `## ${transcriptLink(chat)}`, '');
    out.push(`${chat.date} · ${plural(chat.turns.length, 'turn')} · [open in ChatGPT](${chat.url})${tags(chat)}`, '');
    for (const turn of chat.turns) out.push(`- L${turn.line}: ${truncate(turn.text, MONTH_TURN_LIMIT).text}`);
    if (chat.fallback) out.push(`- L${chat.fallback.line} ${NO_QUESTIONS}: ${chat.fallback.text}`);
    else if (!chat.turns.length) out.push('- (empty conversation)');
  }
  return out.join('\n') + '\n';
}

// ---- Building ----

export interface DigestResult {
  chats: number;
  userTurns: number;
  assistantTurns: number;
  months: number;
  /** Files the digest consists of (INDEX.md, the month pages, index.html). */
  files: number;
  /** How many of them changed and were rewritten. */
  written: number;
  /** Month pages removed because no chat is left in that month. */
  removed: string[];
  /** Markdown file names of chats with no typed messages. */
  silent: string[];
  /** "<file name>: <reason>" for Markdown files that couldn't be read. */
  failures: string[];
  /** Sizes in bytes. */
  bytes: { index: number; months: number; html: number };
}

/** Rewrites a file only when its content changed. */
async function writeIfChanged(file: string, content: string): Promise<boolean> {
  const current = await fs.readFile(file, 'utf-8').catch(() => null);
  if (current === content) return false;
  await writeAtomic(file, content);
  return true;
}

/**
 * Builds <outputDir>/digest from the Markdown in <outputDir>/markdown (top level only: the project
 * folders hold copies of the same chats). Writes nothing when there are no chats yet.
 */
export async function buildDigest(outputDir: string, options: { signal?: AbortSignal } = {}): Promise<DigestResult> {
  const lookups = await loadLookups(outputDir);
  const markdownDir = path.join(outputDir, 'markdown');
  const names = (await fs.readdir(markdownDir).catch(() => [] as string[])).filter((name) => name.endsWith('.md')).sort();
  const chats: Chat[] = [];
  const failures: string[] = [];
  for (const name of names) {
    if (options.signal?.aborted) throw abortError(options.signal);
    const file = `markdown/${name}`;
    try {
      chats.push(buildChat(file, await fs.readFile(path.join(markdownDir, name), 'utf-8'), lookups));
    } catch (error) {
      failures.push(`${name}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  sortNewestFirst(chats);
  const months = groupByMonth(chats);
  const result: DigestResult = {
    chats: chats.length,
    userTurns: chats.reduce((sum, c) => sum + c.turns.length, 0),
    assistantTurns: chats.reduce((sum, c) => sum + c.assistantTurns, 0),
    months: months.length,
    files: 0,
    written: 0,
    removed: [],
    silent: chats.filter((c) => c.turns.length === 0).map((c) => path.posix.basename(c.file)),
    failures,
    bytes: { index: 0, months: 0, html: 0 },
  };
  if (chats.length === 0) return result;

  const outputs = new Map<string, string>([['INDEX.md', renderIndex(months, chats.length)]]);
  months.forEach(([month, list], i) => outputs.set(`${month}.md`, renderMonth(month, list, months[i + 1]?.[0], months[i - 1]?.[0])));
  outputs.set('index.html', renderHtml(chats, path.resolve(outputDir)));

  const digestDir = path.join(outputDir, 'digest');
  await fs.mkdir(digestDir, { recursive: true });
  // A run killed between writing a temp file and renaming it would otherwise leave it for git to pick up.
  await removeStaleTempFiles(digestDir);
  for (const [name, content] of outputs) if (await writeIfChanged(path.join(digestDir, name), content)) result.written += 1;
  result.removed = (await fs.readdir(digestDir)).filter((name) => /^\d{4}-\d{2}\.md$/.test(name) && !outputs.has(name));
  for (const name of result.removed) await fs.rm(path.join(digestDir, name), { force: true });

  const size = (name: string) => Buffer.byteLength(outputs.get(name) ?? '');
  result.files = outputs.size;
  result.bytes = { index: size('INDEX.md'), months: months.reduce((sum, [m]) => sum + size(`${m}.md`), 0), html: size('index.html') };
  return result;
}
